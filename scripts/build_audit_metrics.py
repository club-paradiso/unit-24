"""Generate source/audit figures from stored records, not narrative estimates."""

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AUDIT = ROOT / "data/audit"


def records(path):
    return [json.loads(line) for line in path.read_text().splitlines()]


def generate():
    retrieval = [json.loads(p.read_text()) for p in sorted((AUDIT / "retrieval").glob("*.json"))]
    facts = records(AUDIT / "real_facts.jsonl")
    decisions = records(AUDIT / "real_eligibility.jsonl")
    audits = records(AUDIT / "fact_audit.jsonl")
    by_agency = Counter(f["agency_id"] for f in facts)
    summary = json.loads((AUDIT / "fact_audit_summary.json").read_text())
    expected = {
        "audited": len(audits),
        "meaning_supported": sum(a["exact_meaning_supported"] for a in audits),
        "full_fact_supported": sum(
            a["exact_meaning_supported"] and a["normalized_metadata_correct"] and a["applicability_scope_correct"] for a in audits
        ),
        "learner_safe": sum(a["safe_expected_answer"] for a in audits),
        "locator_correct": sum(a["locator_correct"] for a in audits),
    }
    assert all(summary[k] == v for k, v in expected.items()), "audit summary contradicts fact audit"
    metrics = {
        "agencies_attempted": len(retrieval),
        "strata": dict(Counter(r["bucket"] for r in retrieval)),
        "responses_saved": sum(bool(r["sources"]) for r in retrieval),
        "invalid_saved_responses": sum(bool(r["sources"]) and not r["capture_usable"] for r in retrieval),
        "retrieved_pdfs": sum(r.get("page_count") is not None for r in retrieval),
        "native_pdf_pages": sum(r.get("page_count") or 0 for r in retrieval),
        "real_scanned_pdfs": 0,
        "candidate_facts": len(facts),
        "candidate_types": dict(Counter(f["fact_type"] for f in facts)),
        "eligibility": dict(Counter(e["state"] for e in decisions)),
        "audit": summary,
        "protocols_confirmed_current": 0,
    }
    rows = [
        "# Real-source metrics (generated)",
        "",
        "Generated by `uv run python scripts/build_audit_metrics.py`.",
        "",
        "Saved responses are not equivalent to authoritative protocol documents. All sources remain unverified in the pipeline.",
        "",
        "| Agency | Retrieval | PDF pages | Native text characters | Candidate facts | Scope/quality |",
        "|---|---|---:|---:|---:|---|",
    ]
    notes = {
        "CAN-H01": "Invalid empty HTML, not the requested PDF",
        "CAN-M11": "Invalid HTML error response, not the requested PDF",
        "CAN-S47": "FBI NCIC reference hosted by WSP; not WSP radio protocol",
        "CAN-S37": "State-library catalog, underlying document not acquired",
        "CAN-H07": "County IT radio services, Sheriff applicability unproven",
        "CAN-M10": "Property policy; radio keywords do not establish radio rules",
        "CAN-S12": "Original bytes unavailable; web reader separately inspected",
    }
    for row in retrieval:
        chars = row.get("after_html_fix", {}).get("text_characters", row.get("text_characters", "—"))
        rows.append(
            f"| [{row['name']}]({row['url']}) | {row['status']} | {row.get('page_count') or '—'} | {chars} | "
            f"{by_agency[row['canary_id']]} | {notes.get(row['canary_id'], row['note'])} |"
        )
    rows += [
        "",
        f"Candidates: {len(facts)}. Audited: {len(audits)}. Meaning supported: {expected['meaning_supported']}. "
        f"Complete fact supported: {expected['full_fact_supported']}. Learner-safe: {expected['learner_safe']}.",
        "",
        "Purposive source-comparison audit by GPT-6 Astra, not human acceptance. No statistical recall is claimed. "
        "Page locators refer to physical PDF pages. Four required fact strata are missing; see the audit summary.",
        "",
    ]
    return metrics, "\n".join(rows)


def main():
    metrics, report = generate()
    (AUDIT / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\n")
    (ROOT / "docs/real-source-metrics.md").write_text(report)


if __name__ == "__main__":
    main()
